<h3><FONT FACE="Arial, serif"><FONT SIZE=3 STYLE="font-size: 14pt">Workshop Introduction</FONT></FONT></h3>
<P STYLE="margin-bottom: 0.5cm"><FONT COLOR="#222222"><FONT FACE="Arial, serif"><FONT SIZE=2 STYLE="font-size: 10pt">
Networked information systems permeate modern life. From the ATM to
the tablet computer, they're ubiquitous, as is increasingly their
connectivity to the Internet. Securing these systems is a hard job at
the technical level.  The socio-technical side adds even more
complexity. It is now well-understood that the human side of securing
systems is at least as difficult as the technical side. While great
strides have been made in making systems usable and technically
secure, there is often an inherent contradiction in providing usable
security: security is both an emergent property of the system as a
whole and for some users/system elements/circumstances the aim of
security is explicitly to apply the ultimate opposition of usability:
denial of access.
</FONT></FONT></FONT></p>
<P STYLE="margin-bottom: 0.5cm"><FONT COLOR="#222222"><FONT FACE="Arial, serif"><FONT SIZE=2 STYLE="font-size: 10pt">
This apparent contradiction underpins this workshop, which brings
together researchers from a variety of disciplines including, but not
limited to, computer science, psychology, business studies, to present
and discuss recent advances in enabling systems to provide more easily
usable security and privacy. Highlights of last year's workshop
include a linguistic analysis of passphrases (a proposed replacement
for passwords), a method of developing privacy-preserving registration
databases, a system to advise users on the actual personal information
used and transmitted by Android smartphone applications, and a new
taxonomy of weaknesses in the human factors of cryptographic
protocols.
</FONT></FONT></FONT></p>

