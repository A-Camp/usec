<h3><FONT FACE="Arial, serif"><FONT SIZE=3 STYLE="font-size: 14pt">Keynote Speaker</FONT></FONT></h3>

<P STYLE="margin-bottom: 0.5cm"><FONT COLOR="#222222"><FONT FACE="Arial, serif"><FONT SIZE=2 STYLE="font-size: 10pt">
Kindly sponsored by <A HREF="www.google.com">Google</A>,
<A HREF="http://www.heinz.cmu.edu/~acquisti">Dr Alessandro Acquisti</a> of
<A HREF="http://www.heinz.cmu.edu/">Heinz College</a> at
<A HREF="http://www.cmu.edu/">Carnegie Mellon University</a> will deliver a 
keynote speech at USEC 13:
</FONT></FONT></FONT></p>

<P STYLE="margin-bottom: 0.5cm" align="Center"><FONT COLOR="#222222"><FONT FACE="Arial, serif"><FONT SIZE=2 STYLE="font-size: 10pt"><B>
Confessions of a Privacy Economist</B>
</FONT></FONT></FONT></p>

<P STYLE="margin-bottom: 0.5cm; width: 50%; margin-left: 25%; text-align: justify"><FONT COLOR="#222222"><FONT FACE="Arial, serif"><FONT SIZE=2 STYLE="font-size: 10pt">
What drives people to disclose or protect their personal information? What
are the tangible and intangible consequences of those decisions? In this
talk, I will discuss the transition from the economics to the behavioral
economics of privacy. In particular, I will present and contrast a series of
opposing "frames," or ways to frame and analyze the privacy debate, using
the lenses of behavioral economic research. I will start from frames I have
analyzed in my research (for instance: is privacy really about
"transparency" and "control"?) and progressively move onto less settled, and
perhaps more controversial, frames of the debate.
</FONT></FONT></FONT></p>

